package docgen

import (
	"bytes"
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/fmiquel90/stackd/cli/internal/cmd"
)

// The committed reference must match the command tree. On a mismatch, regenerate it:
// `task cli-docs` (STACKD_UPDATE_DOCS=1 go test ./internal/docgen).
func TestReferenceIsUpToDate(t *testing.T) {
	// Defaults read from the environment show in --help: render with a clean one.
	for _, k := range []string{"STACKD_OUTPUT", "STACKD_URL", "STACKD_TOKEN"} {
		t.Setenv(k, "")
	}
	got, err := Reference(cmd.NewRootCmd(strings.NewReader(""), io.Discard, io.Discard))
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	path := filepath.Join("..", "..", "..", "docs", "guide", "cli-reference.md")
	if os.Getenv("STACKD_UPDATE_DOCS") == "1" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v — generate it with: task cli-docs", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date with the commands — regenerate it with: task cli-docs", path)
	}
}

func TestReferenceCoversEveryCommand(t *testing.T) {
	got, err := Reference(cmd.NewRootCmd(strings.NewReader(""), io.Discard, io.Discard))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"## stackd runs plan", "## stackd config import", "## stackd envs create",
		"](#stackd-runs)", "--repo-secret-stdin",
	} {
		if !bytes.Contains(got, []byte(want)) {
			t.Errorf("reference lacks %q", want)
		}
	}
	if bytes.Contains(got, []byte("Auto generated by spf13/cobra")) {
		t.Error("reference carries a generation date")
	}
}
